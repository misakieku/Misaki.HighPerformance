using Misaki.Highperformance.TypeGenerator.Formatting;

namespace Misaki.Highperformance.TypeGenerator.Emitters.Common;

public static class FileHeaderEmitter
{
    public const string InlineMethodAttribute = "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]";

    public static void EmitHeader(CodeWriter writer)
    {
        writer.WriteLine("// <auto-generated>");
        writer.WriteLine("// This code was generated by Misaki.Highperformance.TypeGenerator.");
        writer.WriteLine("// Do not edit this file manually. Any changes will be lost when regenerated.");
        writer.WriteLine("// </auto-generated>");
        writer.WriteLine();
        writer.WriteLine("#nullable enable");
        writer.WriteLine();
    }
}
